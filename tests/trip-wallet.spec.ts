import { test, expect, type Page } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";

test.use({ reducedMotion: "reduce" });
async function openTrip(page: Page) {
  const menu = page.getByRole("button", { name: "Open navigation", exact: true });
  if (await menu.isVisible()) await menu.click();
  await page.getByRole("button", { name: /^My trip,/ }).click();
}

test("Trip shortlist toggles, survives navigation, removes stops and sends an optional date", async ({ page }, info) => {
  await page.goto("/destinations");
  const colombo = page.locator(".destination-card").filter({ has: page.getByRole("heading", { name: "Colombo", exact: true }) });
  const negombo = page.locator(".destination-card").filter({ has: page.getByRole("heading", { name: "Negombo", exact: true }) });
  await colombo.getByRole("button", { name: "Add to my trip", exact: true }).click();
  await expect(colombo.getByRole("button", { name: "Added to my trip" })).toHaveAttribute("aria-pressed", "true");
  await expect(page.getByRole("dialog")).not.toBeVisible();
  await negombo.getByRole("button", { name: "Add to my trip", exact: true }).click();
  await openTrip(page);
  const dialog = page.getByRole("dialog", { name: "Your wish list. Our local know-how." });
  await expect(dialog).toBeVisible();
  await expect(dialog.locator("li")).toHaveCount(2);
  await expect(dialog.getByLabel("Start date", { exact: true })).not.toBeVisible();
  await dialog.getByRole("button", { name: "Add more details (optional)", exact: true }).click();
  await dialog.getByRole("combobox", { name: "Service", exact: true }).click();
  await dialog.getByRole("option", { name: "Chauffeur for a day", exact: true }).click();
  await expect(dialog.getByLabel("Days", { exact: true })).toHaveCount(0);
  await dialog.getByRole("combobox", { name: "Service", exact: true }).click();
  await dialog.getByRole("option", { name: "Multi-day tour", exact: true }).click();
  await dialog.getByLabel("Start date", { exact: true }).fill("2026-12-22");
  const rowBefore = (await dialog.getByLabel("Travellers", { exact: true }).boundingBox())!;
  await dialog.getByRole("button", { name: "Choose start date", exact: true }).click();
  const rowAfter = (await dialog.getByLabel("Travellers", { exact: true }).boundingBox())!;
  expect(rowAfter.y).toBeCloseTo(rowBefore.y, 0);
  await dialog.getByRole("button", { name: "Next month", exact: true }).click();
  await expect(dialog.getByRole("group", { name: "Choose a date" })).toContainText("January 2027");
  await page.screenshot({ path: `/private/tmp/trip-calendar-${info.project.name}.png`, animations: "disabled" });
  await dialog.getByRole("button", { name: "15 January 2027", exact: true }).click();
  await expect(dialog.getByLabel("Start date", { exact: true })).toHaveValue("2027-01-15");
  await dialog.getByRole("combobox", { name: "Pickup", exact: true }).fill("My guesthouse");
  await dialog.getByLabel("Days", { exact: true }).fill("6");
  await dialog.getByLabel("Travellers", { exact: true }).fill("4");
  await expect(dialog.getByLabel("Places you want to see", { exact: true })).toHaveCount(0);
  const travellersBox = (await dialog.getByLabel("Travellers", { exact: true }).boundingBox())!;
  const vehicleBox = (await dialog.getByRole("combobox", { name: "Vehicle", exact: true }).boundingBox())!;
  expect(Math.abs(travellersBox.y - vehicleBox.y)).toBeLessThan(2);
  expect(travellersBox.width).toBeCloseTo(vehicleBox.width, 0);
  if (info.project.name === "desktop") {
    expect(await dialog.locator(".review-content").evaluate((el) => getComputedStyle(el).overflowY)).toBe("auto");
    expect(await dialog.evaluate((el) => getComputedStyle(el).overflow)).toBe("hidden");
  }
  await expect(dialog.getByRole("button", { name: "Close my trip" })).toBeInViewport();
  await dialog.getByRole("button", { name: "Remove Colombo" }).click();
  let url = new URL((await dialog.getByRole("link", { name: "Send to WhatsApp" }).getAttribute("href"))!);
  expect(url.pathname).toBe("/94775088164");
  expect(url.searchParams.get("text")).toContain("1. Negombo");
  expect(url.searchParams.get("text")).not.toContain("Colombo");
  expect(url.searchParams.get("text")).toContain("Start date: 2027-01-15");
  expect((await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze()).violations).toEqual([]);
  await page.screenshot({ path: `/private/tmp/trip-wallet-${info.project.name}.png`, animations: "disabled" });
  expect(url.searchParams.get("text")).toContain("Pickup: My guesthouse");
  expect(url.searchParams.get("text")).toContain("Days: 6");
  expect(url.searchParams.get("text")).toContain("Travellers: 4");
  await dialog.getByLabel("Start date", { exact: true }).fill("");
  await dialog.getByRole("button", { name: "Hide details" }).click();
  url = new URL((await dialog.getByRole("link", { name: "Send to WhatsApp" }).getAttribute("href"))!);
  expect(url.searchParams.get("text")).toContain("Start date: To discuss");
  await page.keyboard.press("Escape");
  await expect(info.project.name === "mobile" ? page.getByRole("button", { name: "Open navigation" }) : page.locator(".trip-nav-button")).toBeFocused();
  await expect(colombo.getByRole("button", { name: "Add to my trip", exact: true })).toHaveAttribute("aria-pressed", "false");
  await negombo.getByRole("button", { name: "Added to my trip" }).click();
  await expect(page.locator(".trip-nav-button")).toHaveAttribute("aria-label", "My trip, 0 saved ideas");
  await colombo.getByRole("button", { name: "Add to my trip", exact: true }).click();
  await page.locator(".footer-column").filter({ has: page.getByRole("link", { name: "Things to do", exact: true }) }).getByRole("link", { name: "Things to do", exact: true }).click();
  await expect(page).toHaveURL(/things-to-do/);
  await page.locator(".experience-card").first().getByRole("button", { name: "Add to my trip", exact: true }).click();
  await openTrip(page);
  await expect(dialog.locator("li")).toHaveCount(2);
  await expect(dialog.locator("li").first()).toContainText("Colombo");
  await dialog.getByRole("button", { name: /^Remove / }).first().click();
  await dialog.getByRole("button", { name: /^Remove / }).first().click();
  await expect(dialog.getByRole("heading", { name: "Where would you love to go?" })).toBeVisible();
  await expect(dialog.getByRole("link", { name: "Send to WhatsApp" })).toHaveCount(0);
});

test("Vehicle dropdown supports keyboard selection and locations include new regions", async ({ page }, info) => {
  await page.goto("/");
  const pickup = page.getByRole("combobox", { name: "Pickup", exact: true });
  await pickup.fill("Tangalle");
  await page.getByRole("option", { name: "Tangalle Sri Lanka", exact: true }).click();
  const vehicle = page.getByRole("combobox", { name: "Vehicle", exact: true });
  await vehicle.click();
  await expect(page.getByRole("listbox", { name: "Vehicle types" })).toBeVisible();
  await page.screenshot({ path: `/private/tmp/vehicle-menu-${info.project.name}.png`, animations: "disabled" });
  await vehicle.press("End");
  await vehicle.press("Enter");
  await expect(vehicle).toContainText("Executive / Luxury");
  await expect(page.locator(".quote-estimate strong")).toHaveText("On request");
  await vehicle.click();
  await page.getByRole("option", { name: /Family MPV/ }).click();
  await expect(page.locator(".quote-estimate strong")).toHaveText("US$475");
  await page.getByRole("button", { name: "Review my ride", exact: true }).click();
  const dialog = page.getByRole("dialog");
  await expect(dialog.locator(".review-story img").first()).toHaveAttribute("alt", "GoChauffeur");
  await expect(dialog.locator(".review-intro")).toHaveCount(0);
  await dialog.getByRole("button", { name: "Edit my ride" }).click();
  await dialog.getByRole("combobox", { name: "Vehicle", exact: true }).click();
  await dialog.getByRole("option", { name: /Economy/ }).click();
  await dialog.getByRole("button", { name: "Save changes" }).click();
  await expect(dialog.locator(".ride-review")).toContainText("Economy");
  expect((await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze()).violations).toEqual([]);
});
